; FX 1.26 overlay collisions with GTIA modes 9, 10, and 11.
; $0082-$0084: P0+P1 multicolor in modes 9, 10, 11.
; $0085-$0087: P5 in modes 9, 10, 11.
.ORG $2000
DMACTL=$D400
DLISTL=$D402
DLISTH=$D403
NMIEN=$D40E
VCOUNT=$D40B
HPOSP0=$D000
HPOSP1=$D001
HPOSM0=$D004
GRAFP0=$D00D
GRAFP1=$D00E
GRAFM=$D011
PRIOR=$D01B
GRACTL=$D01D
HITCLR=$D01E
MEMACB=$D65D
VIDEO=$D640
XDL0=$D641
XDL1=$D642
XDL2=$D643
COLMASK=$D649
COLDETECT=$D64A
COLCLR=$D64A
RESULTS=$82

START:
 LDA #0
 STA NMIEN
 LDX #5
CLEAR_RESULTS:
 STA RESULTS,X
 DEX
 BPL CLEAR_RESULTS
 LDA #$C0
 STA MEMACB
 LDA #<DISPLAY_LIST
 STA DLISTL
 LDA #>DISPLAY_LIST
 STA DLISTH
 LDA #$22
 STA DMACTL
 LDA #3
 STA GRACTL
 ; Solid standard overlay source at local $00000.
 LDA #1
 LDX #0
FILL:
 STA $4000,X
 STA $4100,X
 INX
 BNE FILL
 ; XDL at local $01000: standard graphics, normal width, repeat 192 lines.
 LDA #$62
 STA $5000
 LDA #8
 STA $5001
 LDA #$BF
 STA $5002
 LDA #0
 STA $5003
 STA $5004
 STA $5005
 STA $5006
 STA $5007
 LDA #$14
 STA $5008
 LDA #$FF
 STA $5009
 LDA #0
 STA $500A
 LDA #$80
 STA $500B
 LDA #0
 STA XDL0
 LDA #$10
 STA XDL1
 STA XDL2
 LDA #5
 STA VIDEO
 LDA #$60
 STA HPOSP0
 STA HPOSP1
 STA HPOSM0
 LDA #1
 STA COLMASK
 ; P0+P1 multicolor; bit 5 plus GTIA mode 9/10/11.
 LDA #$FF
 STA GRAFP0
 STA GRAFP1
 LDA #$60
 JSR SAMPLE
 STA RESULTS
 LDA #$A0
 JSR SAMPLE
 STA RESULTS+1
 LDA #$E0
 JSR SAMPLE
 STA RESULTS+2
 ; P5; remove the players before sampling the next complete field.
 LDA #0
 STA GRAFP0
 STA GRAFP1
 STA HPOSP0
 STA HPOSP1
 LDA #3
 STA GRAFM
 LDA #$50
 JSR SAMPLE
 STA RESULTS+3
 LDA #$90
 JSR SAMPLE
 STA RESULTS+4
 LDA #$D0
 JSR SAMPLE
 STA RESULTS+5
READY:
 JMP READY

; A=GTIA PRIOR. Clear both collision latches and sample a complete new field.
SAMPLE:
 STA PRIOR
WAIT_FRAME:
 LDA VCOUNT
 BNE WAIT_FRAME
 STA HITCLR
 STA COLCLR
WAIT_ACTIVE:
 LDA VCOUNT
 CMP #$40
 BCC WAIT_ACTIVE
 LDA COLDETECT
 RTS

.ORG $3000
DISPLAY_LIST:
 .BYTE $70,$70,$70
 ; ANTIC fetches the untouched local $02000 backdrop.  The XDL source is
 ; local $00000, so normal playfield bytes cannot select a collision bit.
 .BYTE $4F,$00,$60
 .REPT 191
 .BYTE $0F
 .ENDR
 .BYTE $41,<DISPLAY_LIST,>DISPLAY_LIST

.RUN START
